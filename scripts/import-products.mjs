// Turns a QuickBooks "Products and Services" CSV export into api/_products.js.
// Usage: node scripts/import-products.mjs path/to/ProductsServicesList.csv
import { readFileSync, writeFileSync } from 'node:fs';

function parseCSV(text) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += c;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.some(Boolean));
}

const file = process.argv[2];
if (!file) { console.error('Usage: node scripts/import-products.mjs <csv>'); process.exit(1); }
const [head, ...rows] = parseCSV(readFileSync(file, 'utf8').replace(/^﻿/, ''));
const col = name => head.indexOf(name);
const iName = col('Product/Service Name'), iPrice = col('Price'), iDesc = col('Sales Description'), iSup = col('Preferred Supplier');
const seen = new Set();
const out = [];
for (const r of rows) {
  const n = (r[iName] || '').trim();
  if (!n) continue;
  const item = { n };
  const d = (r[iDesc] || '').trim();
  if (d && d.toLowerCase() !== n.toLowerCase()) item.d = d;
  const p = parseFloat(r[iPrice]);
  if (Number.isFinite(p)) item.p = p;
  const v = (r[iSup] || '').trim();
  if (v) item.v = v;
  // Every item is kept. Only rows that are exact copies (same name, description, price and supplier)
  // are skipped; items that share a name but differ in price are both kept.
  const key = JSON.stringify(item).toLowerCase();
  if (seen.has(key)) continue;
  seen.add(key);
  out.push(item);
}
out.sort((a, b) => a.n.localeCompare(b.n, undefined, { sensitivity: 'base' }));
writeFileSync(new URL('../api/_products.js', import.meta.url),
  `// Generated by scripts/import-products.mjs from the QuickBooks product list. Don't edit by hand.\n` +
  `// n = name, d = sales description, p = price, v = preferred supplier\n` +
  `export default ${JSON.stringify(out).replace(/\},\{/g, '},\n{')};\n`);
console.log(`Wrote ${out.length} products (${out.filter(x => x.p != null).length} with a price).`);
